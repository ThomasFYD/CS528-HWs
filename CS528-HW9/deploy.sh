#!/usr/bin/env bash
# Resume with the same .state directory after a partial deployment.
set -euo pipefail
INITIALIZE=yes
source "$(dirname "$0")/settings.sh"
for tool in gcloud kubectl gke-gcloud-auth-plugin ssh-keygen; do command -v "$tool" >/dev/null; done
[[ -s "$CLIENT" ]] || { echo "Set HW9_CLIENT to the instructor's Linux executable." >&2; exit 1; }
gc() { "${GC[@]}" "$@"; }
ensure() {
  local split=0 arg; local check=() create=()
  for arg in "$@"; do
    if [[ "$arg" == :: ]]; then split=1
    elif [[ $split == 0 ]]; then check+=("$arg"); else create+=("$arg"); fi
  done
  gc "${check[@]}" >/dev/null 2>&1 || gc "${create[@]}"
}
gc storage objects describe "gs://$BUCKET/data/0.html" --format='value(size)'
gc iam service-accounts describe "$WEB_SA" --format='value(email)'
gc iam service-accounts describe "$REPORTER_SA" --format='value(email)'
gc services enable compute.googleapis.com container.googleapis.com artifactregistry.googleapis.com cloudbuild.googleapis.com logging.googleapis.com pubsub.googleapis.com iamcredentials.googleapis.com iap.googleapis.com
ensure compute networks describe "$NETWORK" :: compute networks create "$NETWORK" --subnet-mode=custom
ensure compute networks subnets describe "$SUBNET" --region="$REGION" :: compute networks subnets create "$SUBNET" --network="$NETWORK" --region="$REGION" --range=10.86.0.0/20
ensure compute firewall-rules describe "$RUN-iap" :: compute firewall-rules create "$RUN-iap" --network="$NETWORK" --allow=tcp:22 --source-ranges=35.235.240.0/20 --target-tags="$RUN-vm"
ensure pubsub topics describe "$TOPIC" :: pubsub topics create "$TOPIC"
ensure pubsub subscriptions describe "$SUB" :: pubsub subscriptions create "$SUB" --topic="$TOPIC" --ack-deadline=60
gc pubsub topics add-iam-policy-binding "$TOPIC" --member="serviceAccount:$WEB_SA" --role=roles/pubsub.publisher >/dev/null
gc pubsub subscriptions add-iam-policy-binding "$SUB" --member="serviceAccount:$REPORTER_SA" --role=roles/pubsub.subscriber >/dev/null
for kind in node build; do
  ensure iam service-accounts describe "$RUN-$kind@$PROJECT.iam.gserviceaccount.com" :: iam service-accounts create "$RUN-$kind" --display-name="CS528 $RUN $kind"
done
gc projects add-iam-policy-binding "$PROJECT" --member="serviceAccount:$NODE" --role=roles/container.defaultNodeServiceAccount --condition=None >/dev/null
ensure artifacts repositories describe "$RUN" --location="$REGION" :: artifacts repositories create "$RUN" --location="$REGION" --repository-format=docker
for pair in "$NODE:reader" "$BUILDER:writer"; do
  gc artifacts repositories add-iam-policy-binding "$RUN" --location="$REGION" --member="serviceAccount:${pair%:*}" --role="roles/artifactregistry.${pair##*:}" >/dev/null
done
ensure storage buckets describe "gs://$STAGING" :: storage buckets create "gs://$STAGING" --location="$REGION" --uniform-bucket-level-access --soft-delete-duration=0
gc storage buckets add-iam-policy-binding "gs://$STAGING" --member="serviceAccount:$BUILDER" --role=roles/storage.objectAdmin >/dev/null
gc storage buckets add-iam-policy-binding "gs://$STAGING" --member="serviceAccount:$BUILDER" --role=roles/storage.legacyBucketReader >/dev/null
bash build-image.sh
digest=$(cut -d @ -f 2 "$STATE/image")
ensure compute instances describe "$VM" --zone="$ZONE" :: compute instances create "$VM" --zone="$ZONE" --machine-type=e2-small --subnet="$SUBNET" \
  --image-family=ubuntu-2404-lts-amd64 --image-project=ubuntu-os-cloud --boot-disk-size=15GB --boot-disk-type=pd-balanced \
  --service-account="$REPORTER_SA" --scopes=cloud-platform --tags="$RUN-vm" --labels="hw9=$RUN" \
  --metadata=block-project-ssh-keys=TRUE --metadata-from-file=startup-script=vm-startup.sh
ensure container clusters describe "$RUN" --zone="$ZONE" :: container clusters create "$RUN" --zone="$ZONE" --num-nodes=1 --machine-type=e2-standard-2 \
  --disk-type=pd-balanced --disk-size=30 --network="$NETWORK" --subnetwork="$SUBNET" --enable-ip-alias --cluster-ipv4-cidr=/20 --services-ipv4-cidr=/24 \
  --service-account="$NODE" --scopes=cloud-platform --workload-pool="$PROJECT.svc.id.goog" --labels="hw9=$RUN" --release-channel=regular
gc container clusters get-credentials "$RUN" --zone="$ZONE"
kubectl get namespace "$RUN" >/dev/null 2>&1 || kubectl create namespace "$RUN"
k() { kubectl -n "$RUN" "$@"; }
k get serviceaccount web >/dev/null 2>&1 || k create serviceaccount web
gc iam service-accounts add-iam-policy-binding "$WEB_SA" --role=roles/iam.workloadIdentityUser --member="$WI_MEMBER" >/dev/null
k annotate serviceaccount web "iam.gke.io/gcp-service-account=$WEB_SA" --overwrite
if ! k get deployment web >/dev/null 2>&1; then
  k create deployment web --image="$IMAGE@$digest" --port=8080 --replicas=0
fi
k set serviceaccount deployment/web web
k set env deployment/web "PROJECT_ID=$PROJECT" "BUCKET_NAME=$BUCKET" "TOPIC_ID=$TOPIC"
# Use the container name generated by kubectl, which depends on the image URL.
k set image deployment/web "*=$IMAGE@$digest"
k scale deployment/web --replicas=1
k rollout status deployment/web --timeout=6m
k get service web >/dev/null 2>&1 || k expose deployment web --type=LoadBalancer --port=80 --target-port=8080
[[ -f "$STATE/ssh" ]] || ssh-keygen -q -t ed25519 -N '' -f "$STATE/ssh"
ready=no
for attempt in {1..24}; do
  if remote 'test -f /var/tmp/hw9-ready'; then ready=yes; break; fi
  sleep 5
done
[[ "$ready" == yes ]] || { echo "VM startup or IAP SSH is unavailable." >&2; exit 1; }
copy_to_vm reporter.py requirements-reporter.txt install-reporter.sh
"${GC[@]}" compute scp "${SSH[@]}" "$CLIENT" "$VM:~/http-client"
remote "chmod 700 ~/http-client && bash install-reporter.sh '$PROJECT' '$SUB'"
k wait --for=jsonpath='{.status.loadBalancer.ingress[0].ip}' service/web --timeout=8m
ip=$(k get service/web -o jsonpath='{.status.loadBalancer.ingress[0].ip}')
curl --fail --silent --show-error --max-time 12 --retry-max-time 180 --retry 30 --retry-all-errors "http://$ip/data/0.html" -o /dev/null
printf 'HW9 is ready at http://%s\n' "$ip"
